"use client";

import { useCallback } from "react";

type Props = {
  /** Pre-rendered on the server so no QR library reaches the browser bundle. */
  svg: string;
  slug: string;
  url: string;
};

/**
 * A printable QR for the page. In these markets the highest-converting place
 * for a business page link is a sticker on the door or the reception desk, not
 * a social profile — so this is a first-class feature, not a novelty.
 */
export function QrCard({ svg, slug, url }: Props) {
  const download = useCallback(() => {
    const blob = new Blob([svg], { type: "image/svg+xml" });
    const href = URL.createObjectURL(blob);

    const link = document.createElement("a");
    link.href = href;
    link.download = `${slug}-qr.svg`;
    link.click();

    URL.revokeObjectURL(href);
  }, [svg, slug]);

  return (
    <div className="card p-4">
      <h2 className="font-medium">QR code</h2>
      <p className="mt-0.5 text-[13px] text-[color:var(--color-muted)]">
        Print it for your door or reception desk. It opens your page.
      </p>

      <div className="mt-3 flex items-center gap-4">
        <div
          className="h-28 w-28 shrink-0 rounded-lg border border-[color:var(--color-hairline)] p-1.5"
          // Generated by our own server from a URL we control, never user input.
          dangerouslySetInnerHTML={{ __html: svg }}
        />

        <div className="min-w-0">
          <p className="truncate text-[13px] text-[color:var(--color-muted)]">
            {url.replace(/^https?:\/\//, "")}
          </p>
          <button
            type="button"
            onClick={download}
            className="mt-2 rounded-lg border border-[color:var(--color-hairline)] px-3 py-1.5 text-[13px] font-medium"
          >
            Download SVG
          </button>
        </div>
      </div>
    </div>
  );
}
